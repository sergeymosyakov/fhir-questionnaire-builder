// Static, crawlable page for ONE template (templates/<id>.html) — generated, never hand-edited.
import { renderStaticPage, esc, SITE } from './static-page.js';
import { questionsOf, resultsOf, linkHtml, usesLoinc, LOINC_NOTICE } from './template-view.js';

/**
 * @param {object} entry catalog entry
 * @param {object} group its wrapper group
 * @param {{related: object[], more: object[], patterns: object[]}} links related templates, other templates of the category, gallery patterns behind this template
 */
export function renderTemplatePage(entry, group, { related = [], more = [], patterns = [] } = {}) {
  const title = `${entry.name} — FHIR Questionnaire Template`;
  const description = `${entry.description} FHIR Questionnaire with ${usesLoinc(group) ? 'LOINC codes, ' : ''}source and license — insert it in one click.`;
  const questions = questionsOf(group);
  const results = resultsOf(group);
  return renderStaticPage({
    file: `templates/${entry.id}.html`,
    root: '../',
    headerHref: '../templates.html',
    generatedBy: 'Generated by `npm run docs:templates` from templates/. Do not edit by hand.',
    title,
    pageTitle: `${entry.name} FHIR Questionnaire Template | FHIR Questionnaire Builder`,
    description,
    keywords: ['FHIR Questionnaire', entry.name, ...(entry.keywords ?? []), ...(usesLoinc(group) ? ['LOINC'] : []), 'SDC'].join(', '),
    headerTitle: 'Questionnaire templates',
    crumb: entry.name,
    titleTestid: 'tpd-all',
    subtitle: 'Ready-made questionnaire templates you can insert into your own questionnaire.',
    openBuilderTestid: 'tpd-open-builder',
    jsonLd: (url) => [
      {
        '@type': 'WebPage', '@id': `${url}#page`, url, name: title, description, inLanguage: 'en',
        breadcrumb: { '@id': `${url}#breadcrumb` },
        isPartOf: { '@type': 'WebApplication', name: 'FHIR Questionnaire Builder', url: `${SITE}/` },
      },
      {
        '@type': 'BreadcrumbList', '@id': `${url}#breadcrumb`,
        itemListElement: [
          { '@type': 'ListItem', position: 1, name: 'FHIR Questionnaire Builder', item: `${SITE}/` },
          { '@type': 'ListItem', position: 2, name: 'Questionnaire templates', item: `${SITE}/templates.html` },
          { '@type': 'ListItem', position: 3, name: entry.name, item: url },
        ],
      },
    ],
    bodyHtml: `    <h1 data-testid="tpd-title">${esc(title)}</h1>
    <p class="gp-lead">${esc(entry.description)}</p>
    <h2>Scoring</h2>
    <p>${esc(entry.scoring)}</p>
    <h2>Questions</h2>
    <ol data-testid="tpd-questions">
${questions.map((q) => `      <li>${esc(q.text)}${q.options.length ? `<ul>${q.options.map((o) => `<li>${esc(o)}</li>`).join('')}</ul>` : ''}</li>`).join('\n')}
    </ol>
${results.length ? `    <h2>Calculated results</h2>
    <ul data-testid="tpd-results">
${results.map((r) => `      <li>${esc(r)}</li>`).join('\n')}
    </ul>
` : ''}    <h2>Source and license</h2>
    <p class="gp-source" data-testid="tpd-source">Source: ${linkHtml(entry.source, entry.sourceUrl)}</p>
    <p class="gp-source" data-testid="tpd-license">License: ${linkHtml(entry.license, entry.licenseUrl)}</p>
    <p>Provided to save authoring effort, not as medical advice — confirm the scale and its cut-offs for your use case.</p>
    <h2>Use it</h2>
    <ol>
      <li>Download the <a href="${esc(entry.file)}" data-testid="tpd-json">FHIR Questionnaire JSON</a>, or</li>
      <li>open the <a href="../index.html">Builder</a>, choose <strong>+ Add → From template…</strong>, search for “${esc(entry.name)}” and insert it. It arrives as one titled group with its calculations wired, and you can keep editing it.</li>
    </ol>
${patterns.length ? `    <h2>In the calculation gallery</h2>
    <p>The same calculations are available as reusable patterns in the <a href="../gallery.html">calculation gallery</a>:</p>
    <ul>
${patterns.map((p) => `      <li><a href="../gallery.html#${esc(p.id)}" data-testid="tpd-formula-${esc(p.id)}">${esc(p.name)}</a></li>`).join('\n')}
    </ul>
` : ''}${related.length ? `    <h2>Related templates</h2>
    <ul>
${related.map((e) => `      <li><a href="${esc(e.id)}.html" data-testid="tpd-related-${esc(e.id)}">${esc(e.name)}</a></li>`).join('\n')}
    </ul>
` : ''}${more.length ? `    <h2>More templates</h2>
    <ul>
${more.map((e) => `      <li><a href="${esc(e.id)}.html" data-testid="tpd-more-${esc(e.id)}">${esc(e.name)}</a></li>`).join('\n')}
    </ul>
` : ''}${usesLoinc(group) ? `    <p class="gp-source">${LOINC_NOTICE}</p>` : ''}`,
  });
}
