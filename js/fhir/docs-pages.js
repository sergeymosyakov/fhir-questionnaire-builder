// Static, crawlable twin of every docs-viewer page (guide/<id>.html) — generated, never hand-edited.
import { Marked } from 'marked';
import { renderStaticPage, esc, SITE } from './static-page.js';

const slug = (t) => t.toLowerCase().replace(/[^\w]+/g, '-').replace(/^-+|-+$/g, '');
const plain = (html) => html.replace(/<[^>]+>/g, '').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&amp;/g, '&');

/** @returns {{html: string, toc: {depth: number, id: string, text: string}[], summary: string}} */
export function renderDocMarkdown(md, fileToId) {
  const toc = [];
  const seen = new Set();
  const marked = new Marked({
    renderer: {
      // Raw HTML in a page is shown as text, never emitted.
      html: ({ text }) => esc(text),
      heading({ tokens, depth }) {
        const inner = this.parser.parseInline(tokens);
        if (depth < 2 || depth > 3) return `<h${depth}>${inner}</h${depth}>\n`;
        const text = plain(inner);
        const id = slug(text);
        // The docs viewer slugs headings the same way, so a clash would break anchors there too.
        if (!id || seen.has(id)) throw new Error(`docs: heading "${text}" gives an empty or duplicate id "${id}"`);
        seen.add(id);
        toc.push({ depth, id, text });
        return `<h${depth} id="${esc(id)}">${inner}</h${depth}>\n`;
      },
      link({ href, title, tokens }) {
        const inner = this.parser.parseInline(tokens);
        const t = title ? ` title="${esc(title)}"` : '';
        if (/^https?:\/\//i.test(href)) return `<a href="${esc(href)}"${t} target="_blank" rel="noopener noreferrer">${inner}</a>`;
        if (href.startsWith('#') || href.startsWith('mailto:')) return `<a href="${esc(href)}"${t}>${inner}</a>`;
        const [path, hash] = href.split('#');
        const id = fileToId.get(path.split('/').pop());
        if (!id) throw new Error(`docs: link "${href}" is not an http(s) URL, an anchor or a page of the manifest`);
        return `<a href="${esc(`${id}.html${hash ? `#${hash}` : ''}`)}"${t}>${inner}</a>`;
      },
    },
  });
  const html = marked.parse(md);
  const firstPara = /<p>([\s\S]*?)<\/p>/.exec(html)?.[1] ?? '';
  const text = plain(firstPara).replace(/\s+/g, ' ').trim();
  return { html, toc, summary: text.length > 200 ? `${text.slice(0, 197).replace(/\s+\S*$/, '')}…` : text };
}

/** Sidebar `<nav>` content shared by guide pages and the pre-rendered docs.html sidebar. */
export function renderNavHtml(manifest, { hrefOf, activeId = null }) {
  return manifest.sections.map((sec) => `        <div class="doc-nav-section">${esc(sec.label)}</div>
        <ul class="doc-nav-list">
${sec.pages.map((p) => `          <li><a class="doc-nav-link${p.id === activeId ? ' doc-nav-link--active' : ''}" href="${esc(hrefOf(p))}"${p.id === activeId ? ' aria-current="page"' : ''}>${esc(p.title)}</a></li>`).join('\n')}
        </ul>`).join('\n');
}

/**
 * @param {object} manifest docs-site/manifest.json
 * @param {object} page     manifest page entry
 * @param {{html: string, toc: object[], summary: string}} doc  renderDocMarkdown() result
 */
export function renderGuidePage(manifest, page, doc) {
  const pages = manifest.sections.flatMap((s) => s.pages);
  const at = pages.findIndex((p) => p.id === page.id);
  const section = manifest.sections.find((s) => s.pages.includes(page));
  const prev = pages[at - 1];
  const next = pages[at + 1];
  const title = `${page.seoTitle ?? page.title} — FHIR Questionnaire Builder Docs`;
  const description = doc.summary || `${page.title} — documentation of the FHIR Questionnaire Builder.`;
  const pager = (p, rel) => (p ? `<a class="doc-pager-link doc-pager-link--${rel}" rel="${rel}" href="${esc(p.id)}.html" data-testid="guide-${rel}">${rel === 'prev' ? `← ${esc(p.title)}` : `${esc(p.title)} →`}</a>` : '');
  return renderStaticPage({
    file: `guide/${page.id}.html`,
    root: '../',
    headerHref: '../docs.html',
    generatedBy: 'Generated by `npm run docs:guide` from docs-site/. Do not edit by hand.',
    title,
    pageTitle: title,
    description,
    keywords: ['FHIR Questionnaire', page.title, section.label, 'documentation'].join(', '),
    headerTitle: '📘 Documentation',
    crumb: page.title,
    titleTestid: 'guide-docs-link',
    openBuilderTestid: 'guide-open-builder',
    styles: ['css/docs-portal.css'],
    rawBody: true,
    jsonLd: (url) => [
      {
        '@type': 'TechArticle', '@id': `${url}#page`, url, headline: page.title, description, inLanguage: 'en',
        articleSection: section.label,
        breadcrumb: { '@id': `${url}#breadcrumb` },
        isPartOf: { '@type': 'WebApplication', name: 'FHIR Questionnaire Builder', url: `${SITE}/` },
      },
      {
        '@type': 'BreadcrumbList', '@id': `${url}#breadcrumb`,
        itemListElement: [
          { '@type': 'ListItem', position: 1, name: 'FHIR Questionnaire Builder', item: `${SITE}/` },
          { '@type': 'ListItem', position: 2, name: 'Documentation', item: `${SITE}/docs.html` },
          { '@type': 'ListItem', position: 3, name: page.title, item: url },
        ],
      },
    ],
    bodyHtml: `  <div class="doc-layout doc-layout--guide">
    <nav class="doc-sidebar" data-testid="guide-sidebar" aria-label="Documentation navigation">
${renderNavHtml(manifest, { hrefOf: (p) => `${p.id}.html`, activeId: page.id })}
    </nav>
    <main class="doc-main">
      <article class="doc-content" data-testid="guide-content">
${doc.html}
${prev || next ? `        <nav class="doc-pager" aria-label="Previous and next page">${pager(prev, 'prev')}${pager(next, 'next')}</nav>` : ''}
      </article>
    </main>
${doc.toc.length > 1 ? `    <aside class="doc-toc" aria-label="On this page">
      <div class="doc-toc-title">On this page</div>
${doc.toc.map((h) => `      <a class="doc-toc-link doc-toc-link--h${h.depth}" href="#${esc(h.id)}">${esc(h.text)}</a>`).join('\n')}
    </aside>
` : ''}  </div>`,
  });
}
