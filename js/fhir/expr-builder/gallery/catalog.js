// Markdown catalog of EXPR_GALLERY (docs/EXPRESSION-GALLERY.md) — generated, never hand-edited.
// Backslashes first, so the ones added for `|` are not escaped again.
const cell = (s) => String(s).replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/\n/g, ' ');

function inputsOf(pattern) {
  const slots = pattern.slots.map((slot) => {
    const opts = slot.transforms?.length > 1 ? ` (${slot.transforms.map((t) => t.label).join(' / ')})` : '';
    return `${slot.label}${slot.repeatable ? ' (add as many rows as needed)' : ''}${opts}`;
  });
  const consts = (pattern.constants || []).map((c) => `${c.label} (default \`${c.default}\`)`);
  return [...slots, ...consts].map(cell).join('<br>');
}

function resultOf(pattern) {
  if (!pattern.categories) return '';
  return pattern.categories.map((c) => c.label).map(cell).join(' · ');
}

export function renderGalleryCatalog(patterns) {
  const rows = patterns.map((p) =>
    `| **${cell(p.name)}** | ${cell(p.description)}${resultOf(p) ? `<br>Result: ${resultOf(p)}` : ''} | ${inputsOf(p)} | ${cell(p.source)} |`);
  return [
    '# Expression Gallery catalog',
    '',
    '<!-- Generated by `npm run docs:gallery` from js/fhir/expr-builder/gallery/. Do not edit by hand. -->',
    '',
    `Ready-made calculation patterns offered by **📐 Choose from gallery** in the Expression Builder (${patterns.length} patterns).`,
    'Pick a pattern, say which questionnaire item supplies each input, and the resulting FHIRPath is inserted as ordinary, editable text.',
    '',
    '- Where an input offers several units, you choose the unit your item uses and the pattern converts it.',
    '- Where a pattern lists an **answer code** input, it is prefilled with a default; change it if your answers use another code.',
    '- Numeric and date patterns give **no result** until every input is answered, rather than guessing a value; yes/no checklist patterns count an unanswered box as No.',
    '- Date patterns need full dates (year-month-day).',
    '- These are reference calculations to save authoring effort, not medical advice. Check each formula against its source for your use case.',
    '',
    'To add a pattern, see [the gallery README](../js/fhir/expr-builder/gallery/README.md).',
    '',
    '| Pattern | What it computes | Inputs | Source |',
    '|---|---|---|---|',
    ...rows,
    '',
  ].join('\n');
}
