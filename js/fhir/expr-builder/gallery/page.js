// Static, crawlable HTML page for the gallery (gallery.html) — generated, never hand-edited.
import { describeInputs } from './catalog.js';

const SITE = 'https://fhirbuilder.com';
const TITLE = 'FHIRPath Calculation Gallery for FHIR Questionnaires';
const PAGE_TITLE = 'FHIRPath Calculation Gallery | FHIR Questionnaire Builder';
const DESCRIPTION = 'Ready-made, source-referenced clinical calculations for FHIR Questionnaires — BMI, eGFR, Glasgow Coma Scale and many more — as working FHIRPath.';

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');
// `<` escaped so the JSON can never close its own <script> element.
const json = (o) => JSON.stringify(o, null, 2).replace(/</g, '\\u003c');

function card(p) {
  // `x` in an input description (a constant's default) is shown as code
  const inputs = describeInputs(p).map((i) => `<li>${esc(i).replace(/`([^`]*)`/g, '<code>$1</code>')}</li>`).join('');
  const bands = p.categories ? `\n      <p class="gp-bands"><strong>Result:</strong> ${p.categories.map((c) => esc(c.label)).join(' &middot; ')}</p>` : '';
  return `    <section class="gp-card" id="${esc(p.id)}" data-testid="gp-card-${esc(p.id)}">
      <h3>${esc(p.name)}</h3>
      <p>${esc(p.description)}</p>${bands}
      <p class="gp-label">Inputs</p>
      <ul>${inputs}</ul>
      <p class="gp-source">Source: ${esc(p.source)}</p>
    </section>`;
}

export function renderGalleryPage(patterns) {
  const url = `${SITE}/gallery.html`;
  const ld = {
    '@context': 'https://schema.org',
    '@graph': [
      {
        '@type': 'WebPage', '@id': `${url}#page`, url, name: TITLE, description: DESCRIPTION, inLanguage: 'en',
        breadcrumb: { '@id': `${url}#breadcrumb` },
        isPartOf: { '@type': 'WebApplication', name: 'FHIR Questionnaire Builder', url: `${SITE}/` },
        mainEntity: { '@id': `${url}#list` },
      },
      {
        '@type': 'ItemList', '@id': `${url}#list`, name: 'Clinical calculation patterns',
        itemListElement: patterns.map((p, i) => ({ '@type': 'ListItem', position: i + 1, name: p.name, url: `${url}#${p.id}` })),
      },
      {
        '@type': 'BreadcrumbList', '@id': `${url}#breadcrumb`,
        itemListElement: [
          { '@type': 'ListItem', position: 1, name: 'FHIR Questionnaire Builder', item: `${SITE}/` },
          { '@type': 'ListItem', position: 2, name: 'Calculation gallery', item: url },
        ],
      },
    ],
  };
  return `<!DOCTYPE html>
<!-- Generated by \`npm run docs:gallery\` from js/fhir/expr-builder/gallery/. Do not edit by hand. -->
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${esc(PAGE_TITLE)}</title>
  <meta name="description" content="${esc(DESCRIPTION)}">
  <meta name="keywords" content="FHIR Questionnaire, FHIRPath, calculatedExpression, SDC, clinical calculator, BMI, eGFR, Glasgow Coma Scale, FHIR form builder">
  <meta property="og:type"        content="website">
  <meta property="og:title"       content="${esc(TITLE)}">
  <meta property="og:description" content="${esc(DESCRIPTION)}">
  <meta property="og:url"         content="${url}">
  <meta property="og:image"       content="${SITE}/docs/social-preview.png">
  <meta name="twitter:card"        content="summary_large_image">
  <meta name="twitter:title"       content="${esc(TITLE)}">
  <meta name="twitter:description" content="${esc(DESCRIPTION)}">
  <meta name="twitter:image"       content="${SITE}/docs/social-preview.png">
  <link rel="canonical" href="${url}">
  <link rel="icon" type="image/svg+xml" href="favicon.svg">
  <link rel="stylesheet" href="css/page-header.css">
  <link rel="stylesheet" href="css/gallery-page.css">
  <script type="application/ld+json">
${json(ld)}
  </script>
</head>
<body>
  <header class="page-header">
    <div class="page-header-bar">
      <a class="page-header-title" href="gallery.html">📐 <span>Calculation gallery</span></a>
      <a class="page-header-back" href="index.html" data-testid="gp-open-builder">Open the Builder →</a>
    </div>
  </header>
  <main class="gp-main">
    <h1>${esc(TITLE)}</h1>
    <p class="gp-lead">Writing a clinical calculation in FHIRPath by hand — item references, unit conversions, edge cases — is slow and error-prone. The <a href="index.html">FHIR Questionnaire Builder</a> ships a gallery of ready-made calculations: choose one, say which questionnaire item supplies each input, and the builder inserts a working <code>calculatedExpression</code> you can keep editing.</p>
    <h2>How it works</h2>
    <ol>
      <li>In the Builder, open an item's expression editor and choose <strong>Choose from gallery</strong>.</li>
      <li>Pick a calculation and select the questionnaire item for each input (with unit conversion where it applies).</li>
      <li>Insert it — the result is ordinary FHIRPath, exported in the standard SDC calculated-expression extension.</li>
    </ol>
    <p>Calculations give no result until their inputs are answered, rather than guessing a value. They are reference calculations to save authoring effort, not medical advice — check each formula against its source for your use case.</p>
    <h2>Calculations in the gallery</h2>
    <nav class="gp-toc" aria-label="Calculations">
      <ul>
${patterns.map((p) => `        <li><a href="#${esc(p.id)}">${esc(p.name)}</a></li>`).join('\n')}
      </ul>
    </nav>
${patterns.map(card).join('\n')}
  </main>
</body>
</html>
`;
}
