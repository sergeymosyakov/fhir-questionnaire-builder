// Shared shell for generated, crawlable pages (gallery.html, templates.html) — never hand-edited output.
export const SITE = 'https://fhirbuilder.com';

export const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');
// `<` escaped so the JSON can never close its own <script> element.
const json = (o) => JSON.stringify(o, null, 2).replace(/</g, '\\u003c');

function headerTitle(p) {
  const tid = p.titleTestid ? ` data-testid="${esc(p.titleTestid)}"` : '';
  const link = `<a class="page-header-title" href="${esc(p.headerHref ?? p.file)}"${tid}>${esc(p.headerTitle)}</a>`;
  if (!p.crumb) return `      ${link}`;
  return `      <nav class="page-header-crumbs" aria-label="Breadcrumb">
        ${link}
        <span class="page-header-sep" aria-hidden="true">›</span>
        <span class="page-header-current" aria-current="page" data-testid="page-header-current">${esc(p.crumb)}</span>
      </nav>`;
}

/**
 * @param {object} p
 * @param {string} p.file         page path from the site root, e.g. 'gallery.html' or 'templates/phq-9.html'
 * @param {string} [p.root]       relative path back to the site root for nested pages, e.g. '../'
 * @param {string} [p.headerHref] link of the header title (default: the page itself)
 * @param {string} [p.crumb]      current page name: the header title becomes a link followed by `› crumb`
 * @param {string} [p.titleTestid] data-testid of the header title link
 * @param {string} p.generatedBy  text of the "Generated by …" comment
 * @param {string} p.title        og/twitter + h1-level title
 * @param {string} p.pageTitle    <title>
 * @param {string} p.description
 * @param {string} p.keywords
 * @param {string} p.headerTitle  plain title in the page header
 * @param {string} p.subtitle
 * @param {string} p.openBuilderTestid
 * @param {string} p.bodyHtml     <main> content (already escaped)
 * @param {object} p.jsonLd       schema.org @graph content builder: (url) => graph array
 */
export function renderStaticPage(p) {
  const url = `${SITE}/${p.file}`;
  const root = p.root ?? '';
  const ld = { '@context': 'https://schema.org', '@graph': p.jsonLd(url) };
  return `<!DOCTYPE html>
<!-- ${p.generatedBy} -->
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${esc(p.pageTitle)}</title>
  <meta name="description" content="${esc(p.description)}">
  <meta name="keywords" content="${esc(p.keywords)}">
  <meta property="og:type"        content="website">
  <meta property="og:title"       content="${esc(p.title)}">
  <meta property="og:description" content="${esc(p.description)}">
  <meta property="og:url"         content="${url}">
  <meta property="og:image"       content="${SITE}/docs/social-preview.png">
  <meta name="twitter:card"        content="summary_large_image">
  <meta name="twitter:title"       content="${esc(p.title)}">
  <meta name="twitter:description" content="${esc(p.description)}">
  <meta name="twitter:image"       content="${SITE}/docs/social-preview.png">
  <link rel="canonical" href="${url}">
  <link rel="icon" type="image/svg+xml" href="${root}favicon.svg">
  <link rel="stylesheet" href="${root}css/page-header.css">
  <link rel="stylesheet" href="${root}css/gallery-page.css">
  <script type="application/ld+json">
${json(ld)}
  </script>
</head>
<body>
  <header class="page-header">
    <div class="page-header-bar">
${headerTitle(p)}
      <a class="page-header-back" href="${root}index.html" data-testid="${p.openBuilderTestid}">← Back to Builder</a>
    </div>
    <p class="page-header-subtitle">${esc(p.subtitle)}</p>
  </header>
  <main class="gp-main">
${p.bodyHtml}
  </main>
</body>
</html>
`;
}
