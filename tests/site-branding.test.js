// Every public page says which product it belongs to.
import { describe, it, expect } from 'vitest';
import { readFileSync, readdirSync } from 'node:fs';
import { brandLinkHtml, BRAND_NAME, AUTHOR_NAMES } from '../js/core/branding.js';
import { COPYRIGHT_HTML, AUTHORS } from '../js/core/copyright.js';

const read = (name) => readFileSync(new URL(`../${name}`, import.meta.url), 'utf8').replace(/\r\n/g, '\n');
const PUBLIC = [
  'help.html', 'docs.html', 'gallery.html', 'templates.html', 'widget-demo.html', 'questionnaire-check.html', 'settings.html', 'questionnaire-docs.html',
  ...readdirSync(new URL('../guide/', import.meta.url)).map((f) => `guide/${f}`),
  ...readdirSync(new URL('../templates/', import.meta.url)).filter((f) => f.endsWith('.html')).map((f) => `templates/${f}`),
];

describe('branding markup', () => {
  it('the brand link goes home with an accessible name even where only the logo shows', () => {
    const html = brandLinkHtml('../');
    expect(html).toContain('href="../index.html"');
    expect(html).toContain(`aria-label="${BRAND_NAME}"`);
    expect(html).toContain('src="../favicon.svg"');
    expect(html).toContain('<span>FHIR Questionnaire</span> <span>Builder</span>');
  });

  it('names the authors for the page metadata', () => {
    expect(AUTHOR_NAMES).toBe(AUTHORS.map((a) => a.name).join(', '));
  });

  it('keeps the copyright text the app shows', () => {
    expect(COPYRIGHT_HTML).toContain('Sergey Mosyakov');
    expect(COPYRIGHT_HTML).toContain('Huthaifa Khan');
    expect(COPYRIGHT_HTML).toContain('Free to use with attribution');
  });
});

describe('public pages', () => {
  it.each(PUBLIC)('%s carries the brand mark', (file) => {
    const html = read(file);
    expect(html, 'brand').toContain('data-testid="page-brand"');
  });

  it('the generated questionnaire document says it was generated by the builder and carries the copyright', () => {
    const script = read('js/questionnaire-docs-page.js');
    expect(script).toContain('Generated on');
    expect(script).toContain('COPYRIGHT_HTML');
  });

  it('the logo is the favicon, and the shared CSS adds no max-width media query for it', () => {
    expect(read('favicon.svg')).toContain('<svg');
    expect(read('css/page-header.css')).not.toMatch(/@media\s*\(max-width/);
  });
});
